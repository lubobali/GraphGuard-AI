"""Kubernetes pieces for the model on S3 (S5.7).

    python -m graphguard.serving.model_k8s secret   # the reader key as a Secret (stdout)
    python -m graphguard.serving.model_k8s egress   # k8s/networkpolicy-s3.yaml from AWS ranges

The scorer gets a read-only key for `models/` and may reach S3's us-east-1 addresses on
443 -- generated from AWS's published `ip-ranges.json`, not "the internet on 443". If AWS
moves S3 to new ranges, a download fails, the new replica refuses to start and the old
one keeps serving; `just k8s-s3-egress` regenerates the list.
"""

from __future__ import annotations

import base64
import ipaddress
import json
import sys
import urllib.request

from graphguard.config import REPO_ROOT, secrets_dir

NS = "graphguard"
SECRET = "graphguard-model"
RANGES_URL = "https://ip-ranges.amazonaws.com/ip-ranges.json"
POLICY_FILE = REPO_ROOT / "k8s" / "networkpolicy-s3.yaml"
CONSUMER_POLICY_FILE = REPO_ROOT / "k8s" / "networkpolicy-s3-consumer.yaml"
SHADOW_POLICY_FILE = REPO_ROOT / "k8s" / "networkpolicy-s3-shadow.yaml"
REGION = "us-east-1"


def s3_prefixes(ranges: dict, region: str = REGION) -> list[str]:
    """S3's IPv4 ranges in one region, sorted and de-duplicated (pure, tested)."""
    nets = {ipaddress.ip_network(p["ip_prefix"]) for p in ranges["prefixes"]
            if p["service"] == "S3" and p["region"] == region}  # fmt: skip
    return [str(n) for n in sorted(nets)]


def egress_policy(prefixes: list[str], sync_token: str, created: str,
                  name: str = "allow-scorer-s3-egress",
                  selector: str = 'ray.io/is-ray-node: "yes"') -> str:  # fmt: skip
    """The NetworkPolicy YAML (pure, tested): the selected pods -> those ranges, TCP 443 only."""
    blocks = "\n".join(f"        - ipBlock: {{cidr: {p}}}" for p in prefixes)
    return f"""# GENERATED by `just k8s-s3-egress` (graphguard.serving.model_k8s) -- do not edit.
# S5.7: the scorer downloads its model from S3 at startup. It may reach S3's {REGION}
# addresses on 443 and nothing else on the internet. Source: {RANGES_URL}
# syncToken {sync_token}, createDate {created}, {len(prefixes)} prefixes.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: {name}
  namespace: {NS}
spec:
  podSelector:
    matchLabels:
      {selector}
  policyTypes: ["Egress"]
  egress:
    - to:
{blocks}
      ports:
        - {{protocol: TCP, port: 443}}
"""


def secret_manifest(env: dict[str, str]) -> str:
    """The reader key as a Secret, for `kubectl apply -f -` on stdin (pure, tested)."""
    keys = ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_REGION")
    data = {k: base64.b64encode(env[k].encode()).decode() for k in keys}
    return json.dumps({"apiVersion": "v1", "kind": "Secret", "type": "Opaque",
                       "metadata": {"name": SECRET, "namespace": NS}, "data": data})  # fmt: skip


def _env_file(name: str) -> dict[str, str]:
    text = (secrets_dir() / name).read_text()
    return dict(line.split("=", 1) for line in text.splitlines() if "=" in line and line[0] != "#")


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else ""
    if cmd == "secret":
        print(secret_manifest(_env_file("models-reader-aws.env")))
        return 0
    if cmd == "egress":
        with urllib.request.urlopen(RANGES_URL, timeout=30) as r:  # noqa: S310 (fixed AWS URL)
            ranges = json.load(r)
        prefixes = s3_prefixes(ranges)
        if not prefixes:
            raise SystemExit("no S3 ranges found -- refusing to write an empty policy")
        POLICY_FILE.write_text(egress_policy(prefixes, ranges["syncToken"], ranges["createDate"]))
        # The stream consumer downloads the same model (S6.6).
        CONSUMER_POLICY_FILE.write_text(egress_policy(
            prefixes, ranges["syncToken"], ranges["createDate"],
            name="allow-consumer-s3-egress", selector="app: graphguard-consumer"))  # fmt: skip
        SHADOW_POLICY_FILE.write_text(egress_policy(
            prefixes, ranges["syncToken"], ranges["createDate"],
            name="allow-shadow-s3-egress", selector="app: graphguard-shadow"))  # fmt: skip
        print(f"wrote {POLICY_FILE.relative_to(REPO_ROOT)} + consumer + shadow: {len(prefixes)} S3 "
              f"{REGION} prefixes")  # fmt: skip
        return 0
    print(f"usage: {argv[0]} secret|egress")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
