"""The rules layer (S6.8): plain, explainable rules next to the model.

Production fraud/AML systems are hybrids: deterministic rules (the baseline regulators
expect, and a safety net if the model fails), an ML score, and a capacity-limited
investigator queue. Every rule here uses only what is known **before** the transaction --
the same as-of state the model sees -- so it can run live in the consumer.

    velocity            the sender's sends in the last 24 h are in the top 0.1% (training)
    fan_out             the sender has more distinct receivers than 99.9% of senders
    fan_in              the receiver has more distinct senders than 99.9% of receivers
    structuring         just under a round reporting threshold: 9,000 <= amount < 10,000
    new_account_large   a never-seen account on either side, with a top-1% amount
    both_new            both accounts never seen -- FINDING-014's hard rule (to review)

Thresholds come from the **training** window only (`thresholds_from`); the comparison with
the model is measured on validation through `evaluate()` (`python -m graphguard.stream.rules`).
How rules and score combine is ADR 0007: `priority()`.
"""

from __future__ import annotations

import dataclasses
import json
import sys
from dataclasses import asdict, dataclass

import numpy as np
import polars as pl

from graphguard.config import REPO_ROOT

# Generated by `python -m graphguard.stream.rules` from the training window; committed, and
# shipped inside the image (the consumer imports it). Not secret: four quantiles.
THRESHOLDS_MODULE = REPO_ROOT / "src" / "graphguard" / "stream" / "rule_thresholds.py"
RULES = ("velocity", "fan_out", "fan_in", "structuring", "new_account_large", "both_new")
STRUCTURING = (9_000.0, 10_000.0)


@dataclass(frozen=True)
class Thresholds:
    velocity_24h: float
    fan_out: float
    fan_in: float
    large_amount: float
    fitted_on: str = "train window"
    # The alert line (ADR 0007): the queue priority at rank K on validation, so the live
    # queue holds ~K alerts per validation window (~50 h) -- an investigator capacity.
    alert_priority: float = 1.0
    alert_capacity: int = 5_000


def thresholds_from(train: pl.DataFrame) -> Thresholds:
    """Quantiles of the training window's own features (never validation)."""
    q = lambda col, p: float(train[col].quantile(p, interpolation="higher"))  # noqa: E731
    return Thresholds(
        velocity_24h=q("sender_sent_last_24h", 0.999),
        fan_out=q("sender_distinct_out_before", 0.999),
        fan_in=q("receiver_distinct_in_before", 0.999),
        large_amount=q("amount_paid", 0.99),
    )


def fire(f: dict, amount: float, sender_cold: bool, receiver_cold: bool,
         th: Thresholds) -> tuple[str, ...]:  # fmt: skip
    """Which rules fire for one transaction. `f` is the model row (as-of features)."""
    out = []
    if f["sender_sent_last_24h"] > th.velocity_24h:
        out.append("velocity")
    if f["sender_distinct_out_before"] > th.fan_out:
        out.append("fan_out")
    if f["receiver_distinct_in_before"] > th.fan_in:
        out.append("fan_in")
    if STRUCTURING[0] <= amount < STRUCTURING[1]:
        out.append("structuring")
    if (sender_cold or receiver_cold) and amount >= th.large_amount:
        out.append("new_account_large")
    if sender_cold and receiver_cold:
        out.append("both_new")
    return tuple(out)


def priority(score: float, rules: tuple[str, ...]) -> float:
    """Queue order (ADR 0007): a hard rule (both_new) or two rules at once go above every
    model-only alert; otherwise the model's score decides. Higher = sooner."""
    if "both_new" in rules or len(rules) >= 2:
        return 1.0 + score
    return score


def rules_only_rank(rules: tuple[str, ...], amount: float) -> float:
    """The rules-only baseline's ranking: more rules first, larger amounts break ties."""
    return len(rules) + min(amount, 1e12) / 1e13


def save(th: Thresholds) -> None:
    body = ",\n".join(f"    {k}={json.dumps(v) if isinstance(v, str) else repr(v)}"
                       for k, v in asdict(th).items())  # fmt: skip
    THRESHOLDS_MODULE.write_text(
        '"""GENERATED by `python -m graphguard.stream.rules` from the TRAINING window (S6.8)."""\n'
        "\nfrom graphguard.stream.rules import Thresholds\n\n"
        f"THRESHOLDS = Thresholds(\n{body},\n)\n"
    )


def load() -> Thresholds:
    from graphguard.stream.rule_thresholds import THRESHOLDS

    return THRESHOLDS


# --- the measurement --------------------------------------------------------------------
def cold_flags(frame: pl.DataFrame) -> pl.DataFrame:
    """Stream-time cold flags: a side is cold when its account has no earlier transaction in
    either role (the store has never seen it). `frame` holds all history in order."""
    order = frame.with_row_index("_pos")
    first = pl.concat([
        order.select(pl.col("from_account").alias("a"), "_pos"),
        order.select(pl.col("to_account").alias("a"), "_pos"),
    ]).group_by("a").agg(pl.col("_pos").min().alias("_first"))  # fmt: skip
    return (order
            .join(first.rename({"a": "from_account", "_first": "_fs"}), on="from_account")
            .join(first.rename({"a": "to_account", "_first": "_fr"}), on="to_account")
            .with_columns((pl.col("_pos") == pl.col("_fs")).alias("sender_cold"),
                          (pl.col("_pos") == pl.col("_fr")).alias("receiver_cold"))
            .sort("_pos").drop("_pos", "_fs", "_fr"))  # fmt: skip


def measure() -> dict:
    """Rules-only vs model-only vs combined, at the same k, on validation."""
    from graphguard.config import TRANSACTIONS_FILE
    from graphguard.data.loader import load_transactions
    from graphguard.evaluation.dataset import frozen_boundaries
    from graphguard.evaluation.evaluate import evaluate
    from graphguard.models.pipeline import features_for_split
    from graphguard.models.tabular import build_matrix
    from graphguard.serving.model_bundle import ModelBundle

    b = frozen_boundaries()
    lf = load_transactions(TRANSACTIONS_FILE)
    lf = (lf.lazy() if isinstance(lf, pl.DataFrame) else lf).with_row_index("source_row")
    th = thresholds_from(features_for_split(lf, "train", b))
    save(th)
    val = features_for_split(lf, "validation", b)
    flags = cold_flags(lf.filter(pl.col("timestamp") < b[1])
                       .sort("timestamp", maintain_order=True).collect()
                       .select("source_row", "from_account", "to_account"))  # fmt: skip
    val = val.join(flags.select("source_row", "sender_cold", "receiver_cold"), on="source_row")
    bundle = ModelBundle.load(REPO_ROOT / "models" / "production")
    X, y = build_matrix(val, bundle.category_maps)
    model = bundle.model.predict_proba(X.select(bundle.feature_columns).to_numpy())[:, 1]
    fired = [fire(r, r["amount_paid"], r["sender_cold"], r["receiver_cold"], th)
             for r in val.select("sender_sent_last_24h", "sender_distinct_out_before",
                                 "receiver_distinct_in_before", "amount_paid", "sender_cold",
                                 "receiver_cold").iter_rows(named=True)]  # fmt: skip
    amounts = val["amount_paid"].to_numpy()
    rules_rank = np.array([rules_only_rank(f, a) for f, a in zip(fired, amounts, strict=True)])
    combined = np.array([priority(s, f) for s, f in zip(model, fired, strict=True)])
    labels = y.to_numpy()
    ks = (500, 1_000, 5_000)
    th = dataclasses.replace(th, alert_priority=float(np.sort(combined)[-th.alert_capacity]))
    save(th)
    out = {"thresholds": asdict(th), "validation_rows": int(len(labels)),
           "laundering": int(labels.sum())}  # fmt: skip
    for name, s in (("rules_only", rules_rank), ("model_only", model), ("combined", combined)):
        r = evaluate(labels, s, k_values=ks)
        p_at_k = {k: round(v, 4) for k, v in r["precision_at_k"].items()}
        out[name] = {"pr_auc": round(r["pr_auc"], 5), "precision_at_k": p_at_k}

    def caught(scores: np.ndarray) -> set[int]:
        """Laundering rows inside this ranking's top 5,000."""
        top = np.argsort(-scores, kind="stable")[:5000]
        return set(top[labels[top] == 1].tolist())

    # What each catches in its top 5,000 that the other does not.
    tr, tm = caught(rules_rank), caught(model)
    out["top5000_caught"] = {
        "rules_only": len(tr),
        "model_only": len(tm),
        "rules_not_model": len(tr - tm),
        "model_not_rules": len(tm - tr),
    }
    out["fire_rate"] = {r: round(sum(r in f for f in fired) / len(fired), 5) for r in RULES}
    out["fire_precision"] = {
        r: round(float(labels[[r in f for f in fired]].mean()), 5) if any(r in f for f in fired)
        else None for r in RULES}  # fmt: skip
    return out


def main(argv: list[str]) -> int:
    result = measure()
    path = REPO_ROOT / "docs" / "analysis" / "s6.8-rules.json"
    path.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
