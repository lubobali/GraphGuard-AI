"""S7.18: "Try one case" -- three alerts picked by a rule, written to a static file.

    python -m graphguard.demo.tour build      # web/lib/tour.json, from the demo database

The tour page reads only this file: no API call, no AI call, nothing written to the server.
The rule, so the pick is not taste: from the top 60 (each has Claude's second opinion against
both decisions), a money picture of 3-12 payments, at least one model reason (not rules only),
not one of Sam's seeded cases; laundering only when it belongs to a ring (a type to teach). Two
laundering alerts of different ring types and one clean alert -- a visitor who always says
"suspicious" must not score 3 of 3 -- each the lowest rank that qualifies. Order: laundering,
clean, laundering. The answers are only these three alerts', shown after the visitor decides.
"""

from __future__ import annotations

import json
import sys

from graphguard.config import REPO_ROOT
from graphguard.demo import workflow as W

OUT = REPO_ROOT / "web" / "lib" / "tour.json"
TOP = 60
MIN_PAYMENTS, MAX_PAYMENTS = 3, 12
MAX_REASONS = 4  # S8b.1: the rules that flagged it first, then the model's reasons
CHECKED = 211  # the home page's default: 100 checks a day over the window's 2.1 days
REVIEWER = "anthropic/claude-sonnet-5.5"  # the second opinion whose label held up (FINDING-020)


def eligible(c: dict) -> bool:
    return (
        c["rank"] <= TOP
        and MIN_PAYMENTS <= c["payments"] <= MAX_PAYMENTS
        and c["reasons"] >= 1
        and c["reviews"] == 2
        and c["event_id"] not in {d[0] for d in W.DEMO_CASES}
        and (not c["is_laundering"] or c["pattern_type"] is not None)
    )


def pick(candidates: list[dict]) -> list[dict]:
    ok = sorted((c for c in candidates if eligible(c)), key=lambda c: c["rank"])
    clean = [c for c in ok if not c["is_laundering"]][:1]
    rings: list[dict] = []
    for c in ok:
        if c["is_laundering"] and c["pattern_type"] not in {r["pattern_type"] for r in rings}:
            rings.append(c)
    if len(clean) < 1 or len(rings) < 2:
        raise ValueError("the rule found too few tour cases; change the rule, not the count")
    return [rings[0], clean[0], rings[1]]


CANDIDATES = f"""
SELECT t.event_id, t.rank, tr.is_laundering, tr.pattern_type,
  cardinality(e.reasons) AS reasons,
  (SELECT count(*) FROM jsonb_array_elements(s.graph->'edges') x
   WHERE x->>'id' IS NOT NULL) AS payments,
  (SELECT count(*) FROM ai_reviews a WHERE a.event_id = t.event_id AND a.model = %s) AS reviews
FROM transactions t JOIN explanations e USING (event_id) JOIN truth tr USING (event_id)
JOIN subgraphs s USING (event_id)
WHERE t.rank <= {TOP} ORDER BY t.rank
"""

PAYMENT = (
    "event_time", "from_name", "from_bank_name", "to_name", "to_bank_name", "amount_paid",
    "payment_currency", "amount_received", "receiving_currency", "payment_format",
)  # fmt: skip


def build(repo) -> dict:
    cases = []
    for c in pick(repo._all(CANDIDATES, (REVIEWER,))):
        a = repo.alert(c["event_id"])
        ans = repo.answer(c["event_id"])
        shown = {e["id"] for e in a["ring"]["edges"] if e.get("id") is not None}
        cases.append({
            "event_id": a["event_id"], "rank": a["rank"],
            "payment": {k: a[k] for k in PAYMENT},
            "reasons": (list(a["rule_text"]) + list(a["reasons"] or []))[:MAX_REASONS],
            "ring": a["ring"],
            "answer": {"is_laundering": ans["is_laundering"], "pattern_type": ans["pattern_type"],
                       "ring_tx": [i for i in ans["ring_hops"] if i in shown]},
            "reviews": [{"direction": r["direction"], "model": r["model"], "review": r["review"]}
                        for r in a["reviews"] if r["model"] == REVIEWER],
        })  # fmt: skip
    # the honest limit line: what the queue's top CHECKED payments hold (the home page's default)
    found = repo._one("SELECT caught FROM capacity WHERE ranking = 'system' AND k = %s",
                      (CHECKED,))["caught"]  # fmt: skip
    total = repo._one("SELECT count(*) AS n FROM truth WHERE is_laundering")["n"]
    out = {"_note": "S7.18: generated by `python -m graphguard.demo.tour build`; do not edit "
                    "(tests/demo/test_demo_live.py compares it with the database).",
           "limits": {"checked": CHECKED, "found": found, "false_alarms": CHECKED - found,
                      "total": total},
           "cases": cases}  # fmt: skip
    return json.loads(json.dumps(out, default=str))


def main(argv: list[str]) -> int:
    if argv[1:] != ["build"]:
        print(__doc__)
        return 2
    from graphguard.demo.queries import PgRepo

    data = build(PgRepo())
    OUT.write_text(json.dumps(data, indent=1) + "\n")
    print([(c["event_id"], c["rank"], c["answer"]["pattern_type"]) for c in data["cases"]])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
