"""S8b.1: neutral names for the simulator's named banks, for the public site.

    python -m graphguard.demo.banks build      # web/lib/bankNames.js, from the demo database

IBM AMLworld names most banks "<Country> Bank #N", but 468 carry invented US-style names, and
some of those match real banks ("Bank of the West"). A public page about money laundering must
not show a real bank's name, even a simulated one. The site shows each as "USA Bank #N" (N by
the name's alphabetical place), in names, the money picture and AI texts alike. The data, the
model and the checker keep the original names; only the screen changes.
"""

from __future__ import annotations

import json
import re
import sys

from graphguard.config import REPO_ROOT

OUT = REPO_ROOT / "web" / "lib" / "bankNames.js"
HEAD = (
    "// Generated by `python -m graphguard.demo.banks build` (S8b.1). Do not edit.\nexport default "
)
GENERIC = re.compile(r"^[A-Za-z ]+ Bank #[0-9]+$")  # "Russia Bank #21": already neutral
NAMES = "SELECT DISTINCT bank_name FROM accounts WHERE bank_name IS NOT NULL ORDER BY 1"


def mapping(names: list[str]) -> dict[str, str]:
    named = sorted(n for n in names if not GENERIC.match(n))
    return {n: f"USA Bank #{i}" for i, n in enumerate(named, start=1)}


def build(repo) -> dict[str, str]:
    return mapping([r["bank_name"] for r in repo._all(NAMES, ())])


def main(argv: list[str]) -> int:
    if argv[:1] != ["build"]:
        print(__doc__)
        return 2
    from graphguard.demo.queries import PgRepo

    m = build(PgRepo())
    OUT.write_text(HEAD + json.dumps(m, indent=0, sort_keys=True) + ";\n")
    print(f"{len(m)} named banks -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))


def read() -> dict[str, str]:
    """The committed file's mapping."""
    return json.loads(OUT.read_text().removeprefix(HEAD).rstrip().removesuffix(";"))
