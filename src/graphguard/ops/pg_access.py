"""Who may connect to GraphGuard's Postgres, from where (S5b.1).

    just pg-access     # writes docker/postgres/pg_hba.conf (no secrets in it)

One line per service: its own role, its own database, from GraphGuard's Docker network
only, with a SCRAM password. Then everything else is rejected. Nothing is `trust`.
The superuser has no network line at all: admin work goes through the container's
local socket (`docker exec`), still with a password.

The host reaches Postgres through the published port, so host connections arrive from
the network's gateway; only the stale S5.6a SQL catalog (`lakehouse`, the rollback)
connects that way.
"""

from __future__ import annotations

import sys

from graphguard.config import REPO_ROOT

HBA_FILE = REPO_ROOT / "docker" / "postgres" / "pg_hba.conf"
NETWORK = "172.25.0.0/16"  # graphguard-net
GATEWAY = "172.25.0.1/32"  # where host connections through 127.0.0.1:5434 arrive from
PODS = "10.42.0.0/16"  # k3s pods, through the pod-bridge port (S6.6: the stream consumer)

# database -> (role, source or sources)
SERVICES: dict[str, tuple[str, str | tuple[str, ...]]] = {
    "mlflow": ("mlflow_app", NETWORK),
    "lakekeeper": ("lakekeeper", NETWORK),
    "lakekeeper_s56c": ("lakekeeper", NETWORK),  # the S5.6c rollback catalog
    "dex": ("dex", NETWORK),
    "mlflow_auth": ("mlflow_auth", NETWORK),  # MLflow's login store (S5b.7)
    "openfga": ("openfga", NETWORK),
    "lakehouse": ("lakehouse", GATEWAY),  # host-side SQL-catalog rollback only
    # The stream's decisions (S6.6): the consumer pod, and the host for its live tests.
    "stream": ("stream_app", (PODS, GATEWAY)),
    # The investigator demo (S7.1): its owner loads it from the host (just demo-build).
    "demo": ("demo_owner", GATEWAY),
}

# Databases with more than one role (S7.1): each extra role reaches ONLY that database.
# demo_reader: SELECT only (the read API, S7.6); demo_writer: INSERT into verdicts only.
EXTRA_ROLES: dict[str, tuple[tuple[str, tuple[str, ...]], ...]] = {
    "demo": (("demo_reader", (NETWORK, GATEWAY)), ("demo_writer", (NETWORK, GATEWAY))),
}


def roles_by_database() -> dict[str, set[str]]:
    out = {db: {role} for db, (role, _) in SERVICES.items()}
    for db, extras in EXTRA_ROLES.items():
        out.setdefault(db, set()).update(role for role, _ in extras)
    return out


def hba_lines(services: dict[str, tuple[str, str]] = SERVICES) -> list[str]:
    lines = [
        "# Generated by graphguard.ops.pg_access (S5b.1). Edit there, not here.",
        "# TYPE  DATABASE          USER          ADDRESS            METHOD",
        "local   all               all                              scram-sha-256",
    ]
    entries = [(db, role, sources) for db, (role, sources) in services.items()]
    if services is SERVICES:
        entries += [(db, r, src) for db, extras in EXTRA_ROLES.items() for r, src in extras]
    for db, role, sources in entries:
        for source in (sources,) if isinstance(sources, str) else sources:
            lines.append(f"host    {db:<17} {role:<13} {source:<18} scram-sha-256")
    lines += [
        "host    all               all           0.0.0.0/0          reject",
        "host    all               all           ::/0               reject",
    ]
    return lines


def main() -> int:
    HBA_FILE.parent.mkdir(parents=True, exist_ok=True)
    HBA_FILE.write_text("\n".join(hba_lines()) + "\n")
    print(f"wrote {HBA_FILE.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
